//! FerrumData-generated scripts (row edits, imports) in one transaction.

use crate::error::map_sqlx_error;
use ferrumdata_db_driver_api::{DbResult, ScriptStatement};
use ferrumdata_domain::Secret;
use sqlx::{AssertSqlSafe, MySqlPool};

/// Runs every statement or none: a failure, or a statement that affects an
/// unexpected number of rows, rolls the transaction back.
pub async fn execute_script(
    pool: &MySqlPool,
    secret: &Secret,
    statements: &[ScriptStatement],
) -> DbResult<Vec<u64>> {
    let map = |e: sqlx::Error| map_sqlx_error(&e, secret);
    let mut tx = pool.begin().await.map_err(map)?;
    let mut counts = Vec::with_capacity(statements.len());
    for (i, statement) in statements.iter().enumerate() {
        // Generated by FerrumData with quoted identifiers and literals.
        let done = sqlx::raw_sql(AssertSqlSafe(statement.sql.clone()))
            .execute(&mut *tx)
            .await
            .map_err(map)?;
        let affected = done.rows_affected();
        if let Some(error) = statement.mismatch(i, affected) {
            tx.rollback().await.map_err(map)?;
            return Err(error);
        }
        counts.push(affected);
    }
    tx.commit().await.map_err(map)?;
    Ok(counts)
}
