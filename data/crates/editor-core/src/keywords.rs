fn contains(list: &[&str], word: &str) -> bool {
    word.len() <= 32
        && list
            .binary_search(&word.to_ascii_uppercase().as_str())
            .is_ok()
}

#[must_use]
pub fn is_keyword(word: &str) -> bool {
    contains(KEYWORDS, word)
}

#[must_use]
pub fn is_type(word: &str) -> bool {
    contains(TYPES, word)
}

#[must_use]
pub fn is_constant(word: &str) -> bool {
    contains(CONSTANTS, word)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn lists_are_sorted_for_binary_search() {
        for list in [KEYWORDS, TYPES, CONSTANTS, FUNCTIONS] {
            assert!(list.windows(2).all(|w| w[0] < w[1]), "{:?}", list);
        }
        assert!(is_keyword("select") && is_type("Varchar") && is_constant("null"));
        assert!(!is_keyword("users"));
    }
}
